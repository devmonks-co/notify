import {
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  type AnyPgColumn,
} from 'drizzle-orm/pg-core';
import { isNotNull, isNull } from 'drizzle-orm';

const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

/** A user id column of the same SQL type as the app's `users.id` (`uuid` or `text`), so the foreign keys line up. */
const userIdColumn = (usersId: AnyPgColumn) => (name: string) =>
  usersId.getSQLType() === 'uuid' ? uuid(name) : text(name);

/**
 * Drizzle tables for the notify module. Pass the app's users table so the foreign keys point at it;
 * the user id columns take its id's type (`uuid` or `text`). Re-export the result from the app's schema so its drizzle-kit
 * generates the migration:
 *
 *   export const { notifications, devices, notificationPrefs, notificationSettings, notificationDeliveries } =
 *     notifyTables({ users });
 */
export function notifyTables({ users }: { users: { id: AnyPgColumn } }) {
  const userId = userIdColumn(users.id);

  /** In-app inbox. One row per inApp delivery. */
  const notifications = pgTable(
    'notification',
    {
      id: text('id').primaryKey(),
      userId: userId('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
      type: text('type').notNull(),
      title: text('title').notNull(),
      body: text('body').notNull().default(''),
      url: text('url'),
      data: jsonb('data').notNull().default({}),
      /** What it is about (an alert, a message), so "who got X" is a plain indexed lookup. */
      sourceId: text('source_id'),
      /** Who caused it, when a user did. Cleared when that user is deleted. */
      actorId: userId('actor_id').references(() => users.id, { onDelete: 'set null' }),
      readAt: ts('read_at'),
      createdAt: ts('created_at').notNull().defaultNow(),
    },
    (t) => [
      /** Keyset paging: newest first, id breaks ties. */
      index('notification_user_created_idx').on(t.userId, t.createdAt.desc(), t.id.desc()),
      index('notification_user_unread_idx').on(t.userId).where(isNull(t.readAt)),
      /** One row per user for each thing it is about; also the "who got X" lookup. */
      uniqueIndex('notification_source_uq').on(t.type, t.sourceId, t.userId).where(isNotNull(t.sourceId)),
      index('notification_created_idx').on(t.createdAt),
    ],
  );

  /** One row per app install. `id` is generated by the app on first launch and stays stable; the push token may rotate. */
  const devices = pgTable(
    'notify_device',
    {
      id: text('id').primaryKey(),
      userId: userId('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
      /** 'ios' | 'android' */
      platform: text('platform').notNull(),
      token: text('token').notNull(),
      appVersion: text('app_version').notNull().default(''),
      createdAt: ts('created_at').notNull().defaultNow(),
      /** Bumped on every registration. Devices are pruned by it only when the app enables pruneInactiveAfterDays. */
      lastSeenAt: ts('last_seen_at').notNull().defaultNow(),
      /** Consecutive permanent failures; the device is deleted at 3. A success resets it. */
      failureCount: integer('failure_count').notNull().default(0),
    },
    (t) => [uniqueIndex('notify_device_token_uq').on(t.token), index('notify_device_user_idx').on(t.userId)],
  );

  /** Per category and channel switch. A missing row means the app's default. */
  const notificationPrefs = pgTable(
    'notification_pref',
    {
      userId: userId('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
      category: text('category').notNull(),
      channel: text('channel').notNull(),
      enabled: boolean('enabled').notNull(),
    },
    (t) => [primaryKey({ columns: [t.userId, t.category, t.channel] })],
  );

  /** Quiet hours. A missing row means none. Times are local 'HH:MM'. */
  const notificationSettings = pgTable('notification_settings', {
    userId: userId('user_id').primaryKey().references(() => users.id, { onDelete: 'cascade' }),
    quietFrom: text('quiet_from'),
    quietTo: text('quiet_to'),
    updatedAt: ts('updated_at').notNull().defaultNow(),
  });

  /** Audit and dedupe of every planned delivery. The unique idempotency key makes retries and double triggers harmless. */
  const notificationDeliveries = pgTable(
    'notification_delivery',
    {
      id: text('id').primaryKey(),
      idempotencyKey: text('idempotency_key').notNull(),
      type: text('type').notNull(),
      /** No FK: also used for address-only sends (sign-in codes before the account exists), as "email:<address>". */
      userId: text('user_id').notNull(),
      channel: text('channel').notNull(),
      deviceId: text('device_id'),
      /** pending | sent | failed | skipped */
      status: text('status').notNull().default('pending'),
      error: text('error'),
      attempts: integer('attempts').notNull().default(0),
      createdAt: ts('created_at').notNull().defaultNow(),
    },
    (t) => [
      uniqueIndex('notification_delivery_key_uq').on(t.idempotencyKey),
      index('notification_delivery_user_idx').on(t.userId, t.createdAt),
      index('notification_delivery_created_idx').on(t.createdAt),
    ],
  );

  return { notifications, devices, notificationPrefs, notificationSettings, notificationDeliveries };
}

export type NotifyTables = ReturnType<typeof notifyTables>;
